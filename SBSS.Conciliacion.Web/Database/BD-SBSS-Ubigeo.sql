CREATE TABLE #DepMap (dep_cod CHAR(2) PRIMARY KEY, idDepartamento INT NOT NULL);
INSERT INTO #DepMap (dep_cod, idDepartamento)
SELECT u.dep_cod, d.idDepartamento
FROM #Ubigeo u
JOIN Departamento d ON d.nombre = u.nombre
WHERE u.prov_cod = '00' AND u.dist_cod = '00';

-- 2) Provincias (resueltas contra el idDepartamento real, no contra el código)
INSERT INTO Provincia (idDepartamento, nombre)
SELECT dm.idDepartamento, u.nombre
FROM #Ubigeo u
JOIN #DepMap dm ON dm.dep_cod = u.dep_cod
WHERE u.prov_cod <> '00' AND u.dist_cod = '00'
ORDER BY u.dep_cod, u.prov_cod;

CREATE TABLE #ProvMap (dep_cod CHAR(2), prov_cod CHAR(2), idProvincia INT NOT NULL, PRIMARY KEY (dep_cod, prov_cod));
INSERT INTO #ProvMap (dep_cod, prov_cod, idProvincia)
SELECT u.dep_cod, u.prov_cod, p.idProvincia
FROM #Ubigeo u
JOIN #DepMap dm ON dm.dep_cod = u.dep_cod
JOIN Provincia p ON p.idDepartamento = dm.idDepartamento AND p.nombre = u.nombre
WHERE u.prov_cod <> '00' AND u.dist_cod = '00';

-- 3) Distritos (resueltos contra el idProvincia real, vía el par depto+provincia)
INSERT INTO Distrito (idProvincia, nombre)
SELECT pm.idProvincia, u.nombre
FROM #Ubigeo u
JOIN #ProvMap pm ON pm.dep_cod = u.dep_cod AND pm.prov_cod = u.prov_cod
WHERE u.dist_cod <> '00'
ORDER BY u.dep_cod, u.prov_cod, u.dist_cod;

DROP TABLE #ProvMap;
DROP TABLE #DepMap;
DROP TABLE #Ubigeo;

-- Verificación rápida de resultado
SELECT
    (SELECT COUNT(*) FROM Departamento) AS totalDepartamentos,
    (SELECT COUNT(*) FROM Provincia)    AS totalProvincias,
    (SELECT COUNT(*) FROM Distrito)     AS totalDistritos;
